package safety

import "testing"

func TestIsReadOnlyCommand(t *testing.T) {
	cases := []struct {
		cmd  string
		want bool
	}{
		{"go version", true},
		{"ss -ltnp | grep 8500", true},
		{"echo hi 2>/dev/null", true},
		{"echo hi 2>&1", true},
		{"ls", true},
		{"pwd", true},
		{"cat file", true},
		{"head -n 5 f", true},
		{"tail -n 2 f", true},
		{"git status", true},
		{"git log --oneline", true},
		{"git diff", true},
		{"git show HEAD", true},
		{"git branch", true},
		{"git remote -v", true},
		{"git rev-parse HEAD", true},
		{"git ls-files", true},
		{"git blame f", true},
		{"docker ps", true},
		{"docker images", true},
		{"docker logs c", true},
		{"docker inspect c", true},
		{"systemctl status nginx", true},
		{"journalctl -u foo", true},
		{"command -v go", true},
		{"ping -c 1 localhost", true},
		{"ping -c1 host", true},
		{"find . -name '*.go' -maxdepth 2", true},
		{"pacman -Q", true},
		{"pacman -Ss foo", true},
		{"pacman -Qi bash", true},
		{"node -v", true},
		{"node --version", true},
		{"npm ls", true},
		{"npm view pkg", true},
		{"npm -v", true},
		{"pnpm ls", true},
		{"pnpm -v", true},
		{"python3 --version", true},
		{"pip list", true},
		{"pip show pkg", true},
		{"cargo --version", true},
		{"rustc --version", true},
		{"go env GOPATH", true},
		{"go list ./...", true},
		{"go doc fmt", true},
		{"uname -a", true},
		{"whoami", true},
		{"id", true},
		{"hostname", true},
		{"date", true},
		{"uptime", true},
		{"which bash", true},
		{"type ls", true},
		{"env", true},
		{"printenv PATH", true},
		{"ps aux", true},
		{"pgrep ssh", true},
		{"lsof -i :80", true},
		{"ip addr", true},
		{"dig example.com", true},
		{"nslookup example.com", true},
		{"rg foo", true},
		{"sort file | uniq", true},
		{"cut -d: -f1 /etc/passwd", true},
		{"tr a-z A-Z", true},
		{"awk '{print $1}' f", true},
		{"sed s/a/b/ f", true},
		{"jq . file.json", true},
		{"diff a b", true},
		{"cmp a b", true},
		{"md5sum f", true},
		{"sha256sum f", true},
		{"realpath .", true},
		{"readlink f", true},
		{"basename /a/b", true},
		{"dirname /a/b", true},
		{"file f", true},
		{"stat f", true},
		{"du -sh .", true},
		{"df -h", true},
		{"free -h", true},
		{"wc -l f", true},
		{"tree -L 1", true},

		{"git push", false},
		{"sed -i s/a/b/ f", false},
		{"find . -delete", false},
		{"cat a > b", false},
		{"ls $(pwd)", false},
		{"rm x", false},
		{"xargs echo", false},
		{"FOO=1 ls", false},
		{"find . -exec rm {} ;", false},
		{"find . -execdir rm {} ;", false},
		{"find . -ok rm {} ;", false},
		{"find . -fprint /tmp/x", false},
		{"find . -fprintf /tmp/x %p", false},
		{"awk '{system(\"rm x\")}'", false},
		{"echo `pwd`", false},
		{"cat <<EOF", false},
		{"(FOO=1; ls)", false},
		{"git commit", false},
		{"git remote", false},
		{"docker run alpine", false},
		{"npm install", false},
		{"go test", false},
		{"go build", false},
		{"systemctl start nginx", false},
		{"ping google.com", false},
		{"command -p ls", false},
		{"node app.js", false},
		{"python3 app.py", false},
		{"python3 -V", false},
		{"pacman -Syu", false},
		{"cat a >> b", false},
		{"ls &> out", false},
		{"sed 'w out' f", false},
		{"unknowncmd", false},
		{"ls && rm x", false},
		{"echo hi | xargs cat", false},
		{"sudo ls", false},
		{"make", false},
		{"cargo build", false},
		{"pip install x", false},
		{"pnpm install", false},
		{"", false},
		{"true", true},
		{"false", true},
		{`test -e "$HOME/test"`, true},
		{`[ -e "$HOME/test" ]`, true},
		{`[[ -e "$HOME/test" ]]`, true},
		{`if [ -e "$HOME/test" ]; then echo EXISTS; ls -la "$HOME/test"; else echo NO; fi`, true},
		{`if [ -e "$HOME/test" ]; then rm -rf "$HOME/test"; else echo NO; fi`, false},
		{`if [ -e x ]; then echo hi > out; fi`, false},
	}
	if len(cases) < 40 {
		t.Fatalf("need at least 40 cases, have %d", len(cases))
	}
	for _, tc := range cases {
		if got := IsReadOnlyCommand(tc.cmd); got != tc.want {
			t.Errorf("IsReadOnlyCommand(%q) = %v, want %v", tc.cmd, got, tc.want)
		}
	}
}
